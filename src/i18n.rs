//! Internationalization (English and Bahasa Indonesia) strings and language preference.

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Language {
    En,
    Id,
}

impl Language {
    pub fn from_pref(s: &str) -> Self {
        let lower = s.trim().to_ascii_lowercase();
        if lower == "id" || lower == "indonesia" || lower == "indonesian" || lower == "id-id" {
            Language::Id
        } else {
            Language::En
        }
    }

    pub fn as_pref(self) -> &'static str {
        match self {
            Language::En => "en",
            Language::Id => "id",
        }
    }

    pub fn label(self) -> &'static str {
        match self {
            Language::En => "English",
            Language::Id => "Indonesia",
        }
    }

    pub fn is_id(self) -> bool {
        self == Language::Id
    }
}

